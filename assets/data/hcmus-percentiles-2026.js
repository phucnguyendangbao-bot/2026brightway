export function hcmusVactToThpt(value) {
  if (!Number.isFinite(value) || value < 370 || value > 1139) return null;
  for (let i=0;i<hcmusPercentiles.length;i++) {
    const [x,y]=hcmusPercentiles[i];
    if (value===x) return y;
    if (value>x && i>0) {
      const [upperX,upperY]=hcmusPercentiles[i-1];
      return y+(upperY-y)*(value-x)/(upperX-x);
    }
  }
  return null;
}
